import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import ts from "typescript";

const checkOnly = process.argv.includes("--check");
const messagesDirectory = path.resolve("src/features/i18n/messages");
const localesDirectory = path.resolve("src/features/i18n/locales");
const locales = ["en", "es", "fr", "de", "pt", "zh-Hans", "zh-Hant", "ja", "ar", "hi"];
const catalogOrder = [
  "core.ts",
  "drills.ts",
  "benchmarks.ts",
  "exhibits.ts",
  "marketSizing.ts",
  "casePractice.ts",
  "formulas.ts",
  "progress.ts",
  "settings.ts",
  "questionPacks.ts",
  "questioning.ts",
  "experienceQuality.ts",
  "releaseGateGlobal.ts",
  "releaseGateLatin.ts"
];

const availableFiles = new Set(await readdir(messagesDirectory));
const missingFiles = catalogOrder.filter((filename) => !availableFiles.has(filename));
if (missingFiles.length > 0) throw new Error(`Missing i18n catalogs: ${missingFiles.join(", ")}`);
const unlistedFiles = [...availableFiles].filter((filename) => filename.endsWith(".ts") && filename !== "index.ts" && !catalogOrder.includes(filename));
if (unlistedFiles.length > 0) throw new Error(`Unlisted i18n catalogs: ${unlistedFiles.join(", ")}`);

const messages = Object.fromEntries(locales.map((locale) => [locale, {}]));
const registeredDynamicKeys = new Set();

if (!checkOnly) await mkdir(localesDirectory, { recursive: true });

for (const filename of catalogOrder) {
  const source = await readFile(path.join(messagesDirectory, filename), "utf8");
  const javascript = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
    fileName: filename,
    reportDiagnostics: true
  });
  const errors = javascript.diagnostics?.filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error) ?? [];
  if (errors.length > 0) throw new Error(`Could not compile ${filename}: ${errors[0].messageText}`);

  const catalogModule = await import(`data:text/javascript;base64,${Buffer.from(javascript.outputText).toString("base64")}`);
  const catalogs = Object.entries(catalogModule).filter(([name]) => name.endsWith("Messages"));
  if (catalogs.length !== 1) throw new Error(`${filename} must export exactly one *Messages catalog.`);

  const catalog = catalogs[0][1];
  for (const locale of locales) Object.assign(messages[locale], catalog[locale] ?? {});

  for (const [name, value] of Object.entries(catalogModule).filter(([name]) => name.endsWith("DynamicKeys"))) {
    if (!Array.isArray(value) || value.some((key) => typeof key !== "string")) {
      throw new Error(`${filename} export ${name} must be an array of message keys.`);
    }
    for (const key of value) registeredDynamicKeys.add(key);
  }
}

const translatedLocales = locales.filter((locale) => locale !== "en");
const missingDynamicKeys = Object.fromEntries(
  translatedLocales.map((locale) => [
    locale,
    [...registeredDynamicKeys].filter((key) => messages[locale][key] === undefined)
  ])
);
const missingDynamicEntries = Object.entries(missingDynamicKeys).filter(([, keys]) => keys.length > 0);
if (missingDynamicEntries.length > 0) {
  throw new Error(`Missing registered dynamic i18n keys: ${missingDynamicEntries.map(([locale, keys]) => `${locale}: ${keys.join(", ")}`).join("; ")}`);
}

const stale = [];
for (const locale of locales) {
  const outputPath = path.join(localesDirectory, `${locale}.ts`);
  const output = [
    "// Generated by scripts/sync-i18n-locales.mjs. Edit the source catalogs, then run npm run i18n:sync.",
    'import type { Messages } from "@/features/i18n/i18n";',
    "",
    `const messages = ${JSON.stringify(messages[locale])} satisfies Messages;`,
    "",
    "export default messages;",
    ""
  ].join("\n");

  if (checkOnly) {
    const existing = await readFile(outputPath, "utf8").catch(() => "");
    if (existing !== output) stale.push(path.relative(process.cwd(), outputPath));
  } else {
    await writeFile(outputPath, output, "utf8");
  }
}

if (stale.length > 0) {
  throw new Error(`Generated locale files are stale: ${stale.join(", ")}. Run npm run i18n:sync.`);
}

console.log(checkOnly ? "Generated locale files are current." : "Generated locale files updated.");
